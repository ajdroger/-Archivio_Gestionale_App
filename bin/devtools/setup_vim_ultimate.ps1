# Setup VIM Ultimate Environment
# Usage: ./setup_vim_ultimate.ps1

Write-Host ">>> STARTING VIM ULTIMATE SCRIPT <<<" -ForegroundColor Cyan

# 1. Check for VIM
if (-not (Get-Command "vim" -ErrorAction SilentlyContinue)) {
    Write-Host "[-] Vim not found. Attempting installation via Chocolatey..." -ForegroundColor Yellow
    try {
        choco install vim -y
        # Attempt to refresh path from registry
        $env:Path = [System.Environment]::GetEnvironmentVariable("Path","Machine") + ";" + [System.Environment]::GetEnvironmentVariable("Path","User")
        if (-not (Get-Command "vim" -ErrorAction SilentlyContinue)) {
            Write-Warning "Vim installed but not in PATH yet. Please restart your terminal/shell and run this script again."
            exit
        }
    } catch {
        Write-Error "Failed to install Vim. Please install manually (e.g., 'choco install vim -y' as Admin)."
        exit 1
    }
} else {
    Write-Host "[+] Vim detected." -ForegroundColor Green
}

# 2. Directories Setup
$vimDir = "$env:USERPROFILE\.vim"
if (-not (Test-Path $vimDir)) { 
    New-Item -ItemType Directory -Force -Path $vimDir | Out-Null 
    Write-Host "[+] Created .vim directory"
}

$undoDir = "$vimDir\undo"
if (-not (Test-Path $undoDir)) { 
    New-Item -ItemType Directory -Force -Path $undoDir | Out-Null 
    Write-Host "[+] Created persistent undo directory"
}

# 3. Download Vim-Plug
$autoloadDir = "$vimDir\autoload"
if (-not (Test-Path $autoloadDir)) { New-Item -ItemType Directory -Force -Path $autoloadDir | Out-Null }

$plugFile = "$autoloadDir\plug.vim"
if (-not (Test-Path $plugFile)) {
    Write-Host "[*] Downloading vim-plug..."
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri "https://raw.githubusercontent.com/junegunn/vim-plug/master/plug.vim" -OutFile $plugFile
        Write-Host "[+] vim-plug downloaded."
    } catch {
        Write-Error "Failed to download vim-plug. Check internet connection."
        exit 1
    }
}

# 4. Configure _vimrc
$vimrcPath = "$env:USERPROFILE\_vimrc"
if (Test-Path $vimrcPath) {
    Copy-Item $vimrcPath "$vimrcPath.bak" -Force
    Write-Host "[*] Backup created at $vimrcPath.bak" -ForegroundColor Gray
}

$vimrcContent = @"
" --- VIM ULTIMATE CONFIGURATION ---
" Generated by DevTools Script

set nocompatible
filetype plugin indent on

" --- PLUGINS ---
call plug#begin('$($vimDir.Replace('\','/'))/plugged')
    Plug 'preservim/nerdtree'           " File Explorer
    Plug 'vim-airline/vim-airline'      " Status Bar
    Plug 'junegunn/fzf'                 " Fuzzy Finder
    Plug 'airblade/vim-gitgutter'       " Git Diff
    Plug 'neoclide/coc.nvim', {'branch': 'release'} " IntelliSense
    Plug 'ryanoasis/vim-devicons'       " Icons
    Plug 'tpope/vim-surround'           " Surround helper
    Plug 'tpope/vim-commentary'         " Commenter
call plug#end()

" --- SETTINGS ---
syntax on
set number relativenumber
set cursorline
set termguicolors
set scrolloff=8
set expandtab tabstop=4 shiftwidth=4 smartindent
set ignorecase smartcase incsearch hlsearch
set clipboard=unnamedplus
set undofile
set undodir=$($undoDir.Replace('\','/'))

" --- MAPPINGS ---
let mapleader = " "
nnoremap <Leader>w :w<CR>
nnoremap <Leader>q :q<CR>
nnoremap <Leader>e :NERDTreeToggle<CR>
nnoremap <C-h> <C-w>h
nnoremap <C-j> <C-w>j
nnoremap <C-k> <C-w>k
nnoremap <C-l> <C-w>l
nnoremap <F3> :noh<CR>
"@

Set-Content -Path $vimrcPath -Value $vimrcContent
Write-Host "[+] _vimrc updated."

# 5. Install Plugins
Write-Host "[*] Installing plugins via Vim... (closes automatically)"
Start-Process "vim" -ArgumentList "-c","PlugInstall","-c","qa" -Wait

Write-Host ">>> SETUP COMPLETE! <<<" -ForegroundColor Cyan
Write-Host "Run 'vim' to see your new power editor."
